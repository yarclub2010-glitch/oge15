// поэтому решение проверяется на многих вариантах, а не на одной картинке.

import { Field } from '../robot/field.js';

export const LEVELS = {
  1: 'Разминка',
  2: 'Посложнее',
  3: 'Как на ОГЭ',
  4: 'Сложные',
};

const MOVE = { up: 'вверх', down: 'вниз', left: 'влево', right: 'вправо' };
const SIDE = { up: 'сверху', down: 'снизу', left: 'слева', right: 'справа' };
const OPP = { up: 'down', down: 'up', left: 'right', right: 'left' };

// ---------- Параметры вариантов ----------

export function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// pick(a, b) — целое от a до b. mode: 'random' | 'min' | 'max' | 'edge' (крайние значения)
export function makePick(mode, seed) {
  const rng = mulberry32(seed);
  switch (mode) {
    case 'min': return (a) => a;
    case 'max': return (a, b) => b;
    case 'edge': return (a, b) => (rng() < 0.5 ? a : b);
    default: return (a, b) => a + Math.floor(rng() * (b - a + 1));
  }
}

// Проход в стене длины len: несколько подряд идущих клеток, не на концах стены
function passage(len, pick) {
  const width = pick(1, Math.min(3, len - 2));
  const start = pick(1, len - 1 - width);
  return Array.from({ length: width }, (_, i) => start + i);
}

const key = (x, y) => `${x},${y}`;

// ---------- Куски эталонных решений ----------

function indent(lines, n = 1) {
  return lines.map((l) => '  '.repeat(n) + l);
}

function paintAlong(move, side) {
  return [`нц пока не ${SIDE[side]} свободно`, '  закрасить', `  ${MOVE[move]}`, 'кц'];
}

function skipPassage(move, side) {
  return [`нц пока ${SIDE[side]} свободно`, `  ${MOVE[move]}`, 'кц'];
}

// Пройти вдоль всей стены с одним проходом, закрашивая клетки у стены
function wallWithPassage(move, side) {
  return [
    `| закрашиваем клетки до прохода`,
    ...paintAlong(move, side),
    `| проходим проход, не закрашивая`,
    ...skipPassage(move, side),
    `| закрашиваем клетки после прохода`,
    ...paintAlong(move, side),
  ];
}

function program(bodyLines) {
  return ['использовать Робот', 'алг', 'нач', ...indent(bodyLines), 'кон'].join('\n');
}

// ---------- Уголок: горизонтальная и вертикальная стены, соединённые концами ----------
// h: куда от угла уходит горизонтальная стена ('left' | 'right')
// v: куда от угла уходит вертикальная стена ('up' | 'down')
// start: 'h' — Робот у свободного конца горизонтальной стены, 'v' — вертикальной
// outer: закрашивать внешние стороны уголка вместо внутренних

function cornerGenerator({ h, v, start, outer = false, passages = true }) {
  return (pick) => {
    const lenH = pick(4, 11);
    const lenV = pick(4, 8);
    const m = 2;
    const w = lenH + 1 + 2 * m;
    const ht = lenV + 1 + 2 * m;
    const X = h === 'left' ? m + lenH : m + 1;
    const Y = v === 'down' ? m + 1 : m + lenV;
    const f = new Field(w, ht);

    const hCells = Array.from({ length: lenH }, (_, k) => (h === 'left' ? X - 1 - k : X + k));
    const vCells = Array.from({ length: lenV }, (_, k) => (v === 'down' ? Y + k : Y - 1 - k));
    const gapH = passages ? passage(lenH, pick) : [];
    const gapV = passages ? passage(lenV, pick) : [];

    hCells.forEach((x, k) => { if (!gapH.includes(k)) f.hLine(Y, x, x); });
    vCells.forEach((y, k) => { if (!gapV.includes(k)) f.vLine(X, y, y); });

    const innerRow = v === 'down' ? Y : Y - 1;
    const innerCol = h === 'left' ? X - 1 : X;
    const row = outer ? (v === 'down' ? Y - 1 : Y) : innerRow;
    const col = outer ? (h === 'left' ? X : X - 1) : innerCol;

    const target = new Set();
    hCells.forEach((x, k) => { if (!gapH.includes(k)) target.add(key(x, row)); });
    vCells.forEach((y, k) => { if (!gapV.includes(k)) target.add(key(col, y)); });

    f.robot = start === 'h' ? { x: hCells[lenH - 1], y: row } : { x: col, y: vCells[lenV - 1] };
    return { field: f, target };
  };
}

function cornerSolution({ h, v, start, outer = false, passages = true }) {
  // Стена вдоль горизонтальной стены: сторона, где стена относительно Робота
  const hSide = outer ? v : OPP[v];
  const vSide = outer ? h : OPP[h];
  const first = start === 'h'
    ? { move: OPP[h], side: hSide, name: 'горизонтальной' }
    : { move: OPP[v], side: vSide, name: 'вертикальной' };
  const second = start === 'h'
    ? { move: v, side: vSide, name: 'вертикальной' }
    : { move: h, side: hSide, name: 'горизонтальной' };

  const lines = [];
  if (outer) {
    lines.push(`| вдоль ${first.name} стены до её конца`);
    lines.push(...(passages ? wallWithPassage(first.move, first.side) : paintAlong(first.move, first.side)));
    lines.push('| огибаем угол');
    lines.push(MOVE[second.move]);
  } else {
    lines.push(`| вдоль ${first.name} стены до угла`);
    if (passages) {
      lines.push(...paintAlong(first.move, first.side));
      lines.push('| проход');
      lines.push(...skipPassage(first.move, first.side));
    }
    lines.push(`нц пока ${SIDE[first.move]} свободно`, '  закрасить', `  ${MOVE[first.move]}`, 'кц');
    lines.push('закрасить', '| поворачиваем вдоль второй стены', MOVE[second.move]);
  }
  lines.push(`| вдоль ${second.name} стены`);
  lines.push(...(passages ? wallWithPassage(second.move, second.side) : paintAlong(second.move, second.side)));
  return program(lines);
}

function cornerTask(id, level, title, text, cfg, extra = {}) {
  return {
    id,
    level,
    title,
    text,
    generate: cornerGenerator(cfg),
    solution: cornerSolution(cfg),
    ...extra,
  };
}

