// Вариант, который показан «на рисунке» в условии
export function sampleVariant(task) {
  return task.generate(makePick('random', 2025 + task.id.length * 7));
}

// Набор вариантов для проверки: пример, крайние случаи и случайные
export function checkVariants(task) {
  const list = [{ label: 'Как на рисунке', ...sampleVariant(task) }];
  list.push({ label: 'Все размеры минимальные', ...task.generate(makePick('min', 1)) });
  list.push({ label: 'Все размеры максимальные', ...task.generate(makePick('max', 1)) });
  for (let i = 0; i < 4; i++) list.push({ label: `Крайние случаи №${i + 1}`, ...task.generate(makePick('edge', 100 + i)) });
  for (let i = 0; i < 8; i++) list.push({ label: `Случайный вариант №${i + 1}`, ...task.generate(makePick('random', 500 + i)) });
  return list;
}

export function randomVariant(task) {
  return task.generate(makePick('random', Math.floor(Math.random() * 1e9)));
}
